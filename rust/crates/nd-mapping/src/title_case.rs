//! Port of `golang.org/x/text/cases.Title(language.Und)`, which Go uses to
//! title-case performer/performer-id sub-roles
//! (`model/metadata/map_participants.go:80-84`, `:98-100`).
//!
//! Go runs Unicode's title-case algorithm (UAX #24 `toTitlecase`): find word
//! boundaries per UAX #29, title-case the first cased rune of each word,
//! lowercase the rest. `x/text`'s `cases` package uses an *approximation* of
//! word breaking (`golang.org/x/text/cases/info.go:33-76`), which this port
//! mirrors:
//!
//! * **Letter** — alphabetic/numeric/Mark/Format runes: never break between two.
//! * **Mid** — the `cccMidLetter`/`cccMidNumLet`/`cccSingleQuote` set
//!   (`x/text/cases/tables15.0.0.go`): joins letters, but two adjacent Mids
//!   break (`"a.b"` → `A.b`, `"a..b"` → `A..B`).
//! * **Break** — everything else: always breaks (`"1st/2nd"` → `1St/2Nd`).
//!
//! The special-case mappings that differ from Rust's `char::to_uppercase`/
//! `char::to_lowercase` are table-driven ([`crate::title_tables`]); both tables
//! were generated by running the real Go implementation over every scalar value
//! (see `tests/testdata/go_oracle/README.md`), so the remaining gap is exactly
//! "no table entry", which the probe proves is empty. The Greek final-sigma
//! rule (`Σ` → `ς`/`σ`) is reproduced too: `cases` special-cases it
//! (`x/text/cases/map.go`), so `"ΑΣ Β"` title-cases to `Ας Β`.

use crate::title_tables::{LOWER_SPECIAL, TITLE_SPECIAL};

/// The separators Go treats as "Mid" for word breaking
/// (`x/text/cases/tables15.0.0.go`: `cccMidLetter` `.`, `cccMidNumLet` `'`,
/// `cccSingleQuote` `'`). Unknown punctuation defaults to Break, which is what
/// x/text does for anything not in the Mid/Extend tables.
const MID_SEPARATORS: &[char] = &['.', '\'', '\u{2018}', '\u{2019}'];

/// Whether a rune belongs to the Letter break class (ALetter, Hebrew_Letter,
/// Numeric, Extend, ExtendNumLet, Format, ZWJ).
fn is_letter(c: char) -> bool {
    c.is_alphabetic() || c.is_numeric() || is_mark(c) || is_format(c)
}

/// Whether a rune is a Mid separator.
fn is_mid(c: char) -> bool {
    MID_SEPARATORS.contains(&c)
}

/// Mark (Mn/Mc/Me) runes, which x/text groups with Letter (UAX #29 Extend).
fn is_mark(c: char) -> bool {
    let cp = u32::from(c);
    (0x0300..=0x036F).contains(&cp)
        || (0x0483..=0x0489).contains(&cp)
        || (0x0591..=0x05BD).contains(&cp)
        || (0x0610..=0x061A).contains(&cp)
        || (0x064B..=0x065F).contains(&cp)
        || cp == 0x0E31
        || (0x0E34..=0x0E3A).contains(&cp)
        || cp == 0x0EB1
        || (0x0EB4..=0x0EB9).contains(&cp)
        || (0x0F71..=0x0F83).contains(&cp)
        || (0x1AB0..=0x1AFF).contains(&cp)
        || (0x20D0..=0x20F0).contains(&cp)
        || (0xFE20..=0xFE2F).contains(&cp)
}

/// Format (Cf) runes, which x/text groups with Letter.
fn is_format(c: char) -> bool {
    let cp = u32::from(c);
    cp == 0x00ad
        || (0x0600..=0x0605).contains(&cp)
        || cp == 0x061c
        || cp == 0x06dd
        || cp == 0x070f
        || cp == 0x180e
        || (0x200b..=0x200f).contains(&cp)
        || (0x202a..=0x202e).contains(&cp)
        || (0x2060..=0x2064).contains(&cp)
        || (0x2066..=0x206f).contains(&cp)
        || cp == 0xfeff
        || (0xfff9..=0xfffb).contains(&cp)
}

/// Title-case runes (Unicode `Lt`): already title-cased, so a word starting
/// with one is left untouched (`ǅungla` stays `ǅungla`). Go checks
/// `unicode.IsTitle`; these are the complete set from the Go tables.
const TITLE_CASE_RUNES: &[char] = &[
    '\u{01C5}', '\u{01C8}', '\u{01CB}', '\u{01F2}', '\u{1F88}', '\u{1F89}', '\u{1F8A}', '\u{1F8B}',
    '\u{1F8C}', '\u{1F8D}', '\u{1F8E}', '\u{1F8F}', '\u{1F98}', '\u{1F99}', '\u{1F9A}', '\u{1F9B}',
    '\u{1F9C}', '\u{1F9D}', '\u{1F9E}', '\u{1F9F}', '\u{1FA8}', '\u{1FA9}', '\u{1FAA}', '\u{1FAB}',
    '\u{1FAC}', '\u{1FAD}', '\u{1FAE}', '\u{1FAF}', '\u{1FBC}', '\u{1FCC}', '\u{1FFC}',
];

/// Whether a rune is already a title-case letter (Go `unicode.IsTitle`).
fn is_title_case(c: char) -> bool {
    TITLE_CASE_RUNES.contains(&c)
}

/// Greek sigma, whose lower mapping depends on whether it ends a word
/// (`x/text/cases/map.go` sigma handling).
fn is_greek_sigma(c: char) -> bool {
    matches!(c, '\u{03a3}' | '\u{03c3}' | '\u{03c2}')
}

/// Title-cases `s` the way `cases.Title(language.Und).String(s)` does.
#[must_use]
pub fn title_case(s: &str) -> String {
    if s.is_empty() {
        return String::new();
    }
    let chars: Vec<char> = s.chars().collect();

    // Pass 1: mark word starts. Text begins a word; a Letter-class rune keeps
    // the current word open; a Mid joins letters but two adjacent Mids break;
    // anything else breaks.
    let mut word_start = vec![false; chars.len()];
    let mut in_word = false;
    let mut prev: Option<char> = None;
    for (i, &c) in chars.iter().enumerate() {
        if is_letter(c) {
            word_start[i] = !in_word;
            in_word = true;
        } else if is_mid(c) {
            word_start[i] = !in_word;
            // Two consecutive Mids break the word (Go: `a..b` -> `A..B`).
            in_word = !prev.is_some_and(is_mid);
        } else {
            word_start[i] = false;
            in_word = false;
        }
        prev = Some(c);
    }

    // Pass 2: the last cased rune of each word, needed for the final-sigma rule.
    let mut word_end = vec![None; chars.len()];
    {
        let mut i = 0usize;
        while i < chars.len() {
            if word_start[i] {
                let mut last_cased = None;
                let mut j = i;
                while j < chars.len() && (j == i || !word_start[j]) {
                    if chars[j].caseable() {
                        last_cased = Some(j);
                    }
                    j += 1;
                }
                word_end[i] = last_cased;
                i = j;
            } else {
                i += 1;
            }
        }
    }

    let mut out = String::with_capacity(s.len());
    // Only the first *cased* rune of a word is title-cased (`1way` -> `1Way`),
    // so the counter — not "am I inside a word" — decides.
    let mut prev: Option<char> = None;
    let mut cased_in_word = 0usize;
    let mut word_last_cased = 0usize;

    for (i, &c) in chars.iter().enumerate() {
        if word_start[i] {
            cased_in_word = 0;
            word_last_cased = word_end[i].unwrap_or(i);
        }

        if is_title_case(c) {
            // A word that starts with an already-title-cased rune keeps it
            // verbatim, and the rest of the word lowercases.
            cased_in_word += 1;
            out.push(c);
        } else if c.caseable() {
            let title_this = cased_in_word == 0;
            cased_in_word += 1;
            if !title_this {
                if is_greek_sigma(c) && i == word_last_cased && cased_in_word > 1 {
                    out.push('\u{03c2}'); // final sigma
                } else if is_greek_sigma(c) {
                    out.push('\u{03c3}');
                } else {
                    out.extend(lower(c));
                }
            } else {
                out.extend(title(c));
            }
        } else if is_letter(c) {
            // Non-cased Letter-class rune (digits, marks, formats): copied; it
            // neither title-cases nor closes the word.
            out.push(c);
        } else if is_mid(c) {
            out.push(c);
            if prev.is_some_and(is_mid) {
                // Two adjacent Mids close the word, so the next cased rune
                // starts a new one (`a..b` -> `A..B`).
                cased_in_word = 0;
            }
        } else {
            out.push(c);
            cased_in_word = 0;
        }
        prev = Some(c);
    }
    out
}

/// `char::is_lowercase() || char::is_uppercase()`: Go's map functions act on any
/// cased rune (title-case mappings aside).
trait Caseable {
    fn caseable(self) -> bool;
}

impl Caseable for char {
    fn caseable(self) -> bool {
        self.is_lowercase() || self.is_uppercase()
    }
}

/// Go's title mapping for one rune: the table value when it differs from Rust's.
fn title(c: char) -> impl Iterator<Item = char> {
    match TITLE_SPECIAL.binary_search_by_key(&c, |(r, _)| *r) {
        Ok(i) => TITLE_SPECIAL[i]
            .1
            .chars()
            .collect::<Vec<char>>()
            .into_iter(),
        Err(_) => c.to_uppercase().collect::<Vec<char>>().into_iter(),
    }
}

/// Go's lower mapping for one rune: the table value when it differs from Rust's.
fn lower(c: char) -> impl Iterator<Item = char> {
    match LOWER_SPECIAL.binary_search_by_key(&c, |(r, _)| *r) {
        Ok(i) => LOWER_SPECIAL[i]
            .1
            .chars()
            .collect::<Vec<char>>()
            .into_iter(),
        Err(_) => c.to_lowercase().collect::<Vec<char>>().into_iter(),
    }
}

/// Title-cases `s`, returning `None` for an empty input (Go's `Title("").String()`
/// is empty, and an empty sub-role is not stored).
#[must_use]
pub fn title_case_option(s: &str) -> Option<String> {
    if s.is_empty() {
        None
    } else {
        Some(title_case(s))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Golden values captured from the real Go implementation
    /// (`cases.Title(language.Und).String`, `golang.org/x/text v0.42.0`).
    #[test]
    fn golden_title_case_pairs() {
        let cases: &[(&str, &str)] = &[
            // Performer sub-roles seen in MusicBrainz-style tags.
            ("guitar", "Guitar"),
            ("gUITAR", "Guitar"),
            ("background vocals", "Background Vocals"),
            ("hammond organ", "Hammond Organ"),
            ("drums (drum set) and organ", "Drums (Drum Set) And Organ"),
            (
                "alto saxophone, baritone saxophone and tenor saxophone",
                "Alto Saxophone, Baritone Saxophone And Tenor Saxophone",
            ),
            ("vocals", "Vocals"),
            ("rhodes piano", "Rhodes Piano"),
            ("b.b. king", "B.b. King"),
            ("", ""),
            // Word-break classes: Mid joins, two Mids break, others break.
            ("a.b", "A.b"),
            ("a..b", "A..B"),
            ("x..y.z", "X..Y.z"),
            ("a''b", "A''B"),
            ("a'b", "A'b"),
            ("'a'", "'A'"),
            ("1way", "1Way"),
            ("dj-mix", "Dj-Mix"),
            ("1st/2nd", "1St/2Nd"),
            ("2nd place", "2Nd Place"),
            ("a b", "A B"),
            ("  x", "  X"),
            ("...x", "...X"),
            ("x...", "X..."),
            // Accents and case-mapping specials.
            ("élan", "Élan"),
            ("óf", "Óf"),
            ("Élan", "Élan"),
            ("ÉLAN", "Élan"),
            ("ß", "Ss"),
            ("STRASSE", "Strasse"),
            ("ﬁle", "File"),
            ("ǅungla", "ǅungla"),
            ("Ǆungla", "ǅungla"),
            ("ǆungla", "ǅungla"),
            ("İstanbul", "İstanbul"),
            // Greek final sigma (`cases` special-cases it).
            ("ΑΣΒ", "Ασβ"),
            ("ΑΣ", "Ας"),
            ("ΑΣ Β", "Ας Β"),
            ("Σ", "Σ"),
            ("ΣΣ", "Σς"),
            ("Σβ", "Σβ"),
            ("ΙΣ", "Ις"),
            ("ἲωρα", "Ἲωρα"),
        ];
        for (input, expected) in cases {
            assert_eq!(&title_case(input), expected, "title_case({input:?})");
        }
    }

    #[test]
    fn empty_input_is_none() {
        assert_eq!(title_case_option(""), None);
        assert_eq!(title_case_option("guitar").as_deref(), Some("Guitar"));
    }
}
